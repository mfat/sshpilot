#!/usr/bin/env python3
"""Write the local-test Flatpak manifest from the Flathub one.

flatpak/io.github.mfat.sshpilot.yaml is an exact copy of the manifest in the
Flathub repository (flathub/io.github.mfat.sshpilot), plus build changes that
ship with the next release; the release workflow publishes it there with the
release's commit pinned. This derives the manifest for building the working
tree, at the repo root (where GNOME Builder looks for it), every time:

- the sshPilot module builds this checkout (type: dir) instead of a pinned
  git commit;
- the Python dependencies module is found in flatpak/.

The output is generated and ignored by git; change the Flathub copy instead.

    python3 scripts/flatpak-dev-manifest.py   # writes io.github.mfat.sshpilot.yaml
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "flatpak" / "io.github.mfat.sshpilot.yaml"
OUTPUT = ROOT / "io.github.mfat.sshpilot.yaml"

HEADER = """\
# GENERATED by scripts/flatpak-dev-manifest.py from flatpak/io.github.mfat.sshpilot.yaml
# (the copy of the Flathub manifest). Builds this working tree; do not edit.
"""

#: The sshPilot git source, with its optional "#tag:" comment and pinned commit.
_GIT_SOURCE = re.compile(
    r'(?P<indent>[ \t]*)- type: git[ \t]*\n'
    r'[ \t]*url:\s*"?https://github\.com/mfat/sshpilot\.git"?[ \t]*\n'
    r'(?:[ \t]*#tag:[^\n]*\n)?'
    r'[ \t]*commit:[ \t]*[0-9a-fA-F]+[ \t]*\n?'
)


def _dir_source(indent: str) -> str:
    body = indent + "  "
    return (
        f"{indent}- type: dir\n"
        f"{body}path: .\n"
        f"{body}# Flathub builds from git, so it only sees tracked files; skip\n"
        f"{body}# local build output to stay close to a clean checkout.\n"
        f"{body}skip:\n"
        + "".join(f"{body}  - {name}\n" for name in (
            ".flatpak-builder", ".git", ".venv", "venv", "builddir", "build", "repo", ".history",
        ))
    )


def dev_manifest(text: str) -> str:
    text, count = _GIT_SOURCE.subn(lambda m: _dir_source(m.group("indent")), text, count=1)
    if count != 1:
        raise SystemExit("could not find the sshPilot git source in the Flathub manifest")
    text, count = re.subn(r"^(\s*)- python3-deps\.yml[ \t]*$", r"\1- flatpak/python3-deps.yml",
                          text, count=1, flags=re.M)
    if count != 1:
        raise SystemExit("could not find the python3-deps.yml module in the Flathub manifest")
    return HEADER + text


def main() -> int:
    OUTPUT.write_text(dev_manifest(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
    print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
